// Imports the original single-file HealthWiz build into the multi-file layout.
//
//   node tools/import-original.mjs legacy/HealthWiz_Kingdom_5-4-3.html
//
// What it does, without changing any behaviour of the original:
//   1. Embedded base64 images (≈800 KB) → files in assets/img/, referenced by relative path.
//   2. The single <script> is cut ONLY between top-level statements (parsed with acorn)
//      into files of ≤ ~60 KB, so no file is large enough to be truncated by a paste again.
//   3. index.html keeps the original markup + stylesheet byte-for-byte and loads the parts in order.
// Re-running it overwrites index.html, js/hw-*.js and assets/img/ — including every intentional
// edit made to js/hw-*.js since the import (see git history / docs). Only re-run on a fresh original.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const req = createRequire(import.meta.url);
let acorn;
try { acorn = req('acorn'); } catch { acorn = req('/opt/node-tools/node_modules/acorn'); }

const src = process.argv[2];
if (!src) { console.error('usage: node tools/import-original.mjs <original.html>'); process.exit(1); }
let html = fs.readFileSync(src, 'utf8');

/* ---------- 1. images ---------- */
const imgDir = path.join(root, 'assets', 'img');
fs.rmSync(imgDir, { recursive: true, force: true });
fs.mkdirSync(imgDir, { recursive: true });
const EXT = { webp: 'webp', png: 'png', jpeg: 'jpg', gif: 'gif' };
const byData = new Map(), used = new Set();
html = html.replace(/data:image\/([a-z+]+);base64,([A-Za-z0-9+/=]+)/g, (m, mime, b64, off, all) => {
  if (byData.has(m)) return byData.get(m);
  const before = all.slice(Math.max(0, off - 160), off);
  // Name from context: `const X='…'` / `, X='…'` → x; `{k:'…'}` → <const>-k; SVG <image id|class=… href> → <const>-id
  const ci = all.lastIndexOf('const ', off), owner = (all.slice(ci).match(/^const (\w+)/) || [, 'img'])[1];
  const decl = before.match(/(?:const |,)(\w+)='$/), key = before.match(/[{,](\w+):'$/),
    svgId = before.match(/<image (?:id|class)="([\w-]+)"[^<>]*href="$/);
  let name = decl ? decl[1] : key ? (owner === 'AVI' ? 'avatar' : owner) + '-' + key[1] : svgId ? owner + '-' + svgId[1] : owner;
  name = name.toLowerCase();
  let n = name, i = 2;
  while (used.has(n)) n = name + '-' + i++;
  used.add(n);
  const file = n + '.' + (EXT[mime] || mime);
  fs.writeFileSync(path.join(imgDir, file), Buffer.from(b64, 'base64'));
  const rel = 'assets/img/' + file;
  byData.set(m, rel);
  return rel;
});

/* ---------- 2. script ---------- */
const open = html.indexOf('<script>'), close = html.lastIndexOf('</script>');
if (open < 0 || close < 0) throw new Error('no inline <script> found');
const head = html.slice(0, open).replace(/\n?$/, '\n');
const code = html.slice(open + '<script>'.length, close).replace(/^\n/, '');
const ast = acorn.parse(code, { ecmaVersion: 'latest', sourceType: 'script' });

const LIMIT = 60_000;
const parts = [];
let cur = { start: 0, end: 0, label: '' };
const label = s => {
  const m = s.match(/\/\*\s*(?:=+|-+)?\s*([^*\n]*?)\s*(?:=+|-+)?\s*\*\//);
  return m ? m[1].replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase().slice(0, 30) : '';
};
const body = ast.body;
body.forEach((node, idx) => {
  const gapStart = idx ? body[idx - 1].end : 0;
  const text = code.slice(gapStart, node.end);
  const isMenu = node.type === 'VariableDeclaration' && node.declarations[0]?.id?.name === 'MENU';
  const isBoot = idx === body.length - 1 && code.slice(node.start, node.end).trim() === 'render();';
  const sectionStart = /\/\*\s*=+/.test(code.slice(gapStart, node.start)); // "/* ===== vX MODULE ===== */"
  if (isMenu || isBoot) {
    if (cur.end > cur.start) parts.push(cur);
    parts.push({ start: gapStart, end: node.end, fixed: isMenu ? 'menu' : 'boot' });
    cur = { start: node.end, end: node.end, label: '' };
    return;
  }
  if (cur.end > cur.start && (sectionStart || cur.end - cur.start + text.length > LIMIT)) {
    parts.push(cur);
    cur = { start: gapStart, end: gapStart, label: '' };
  }
  if (cur.end === cur.start) cur.label = label(code.slice(gapStart, node.start)) || (parts.some(p => !p.fixed) ? 'part' : 'core');
  cur.end = node.end;
});
if (cur.end > cur.start) parts.push(cur);

const jsDir = path.join(root, 'js');
fs.mkdirSync(jsDir, { recursive: true });
for (const f of fs.readdirSync(jsDir)) if (/^hw-\d/.test(f)) fs.rmSync(path.join(jsDir, f));
const files = parts.map((p, i) => {
  const nm = p.fixed === 'menu' ? 'menu-data' : p.fixed === 'boot' ? 'boot' : (p.label || 'part');
  const file = `hw-${String(i + 1).padStart(2, '0')}-${nm}.js`;
  const body = code.slice(p.start, p.end).replace(/^\n+/, '');
  fs.writeFileSync(path.join(jsDir, file), `/* HealthWiz original (${path.basename(src)}), part ${i + 1}/${parts.length} — generated by tools/import-original.mjs; edit freely, but keep load order. */\n${body}\n`);
  return { file, size: body.length };
});

/* ---------- 3. index.html ---------- */
// js/v6-safety.js must run after every page is defined and before the boot call.
const tags = files.map(f => (f.file.endsWith('-boot.js') ? '<script src="js/v6-events.js"></script>\n<script src="js/v6-ui.js"></script>\n<script src="js/v6-insights.js"></script>\n<script src="js/v6-quests.js"></script>\n<script src="js/v6-streaks.js"></script>\n<script src="js/v6-xp.js"></script>\n<script src="js/v6-kingdom.js"></script>\n<script src="js/v6-medius.js"></script>\n<script src="js/v6-charts.js"></script>\n<script src="js/v6-world.js"></script>\n<script src="js/v6-safety.js"></script>\n' : '') + `<script src="js/${f.file}"></script>` + (f.file.endsWith('-menu-data.js') ? '\n<script src="js/v6-schema.js"></script>' : '')).join('\n');
fs.writeFileSync(path.join(root, 'index.html'), head + tags + '\n</body></html>\n');

console.log(`images: ${byData.size} → assets/img/ (${[...used].join(', ')})`);
for (const f of files) console.log(`  ${f.file.padEnd(40)} ${(f.size / 1024).toFixed(1)} KB`);
